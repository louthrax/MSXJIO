; FCB functions test for the JIO remote file system
BDOS	EQU	5
DTA	EQU	80H

	ORG	100H

	LD	DE,MSG_OPEN
	CALL	PRINT
	LD	DE,FCB1
	LD	C,0FH		; open
	CALL	BDOS
	CALL	HEX
	LD	DE,DTA
	LD	C,1AH		; set DTA
	CALL	BDOS
	LD	DE,FCB1
	LD	C,14H		; sequential read
	CALL	BDOS
	CALL	HEX
	LD	HL,DTA
	LD	B,26
	CALL	PRTN
	CALL	CRLF
	LD	DE,MSG_SIZE	; FCB file size (bytes 16..19)
	CALL	PRINT
	LD	A,(FCB1+16)
	CALL	HEX
	LD	DE,FCB1
	LD	C,10H		; close
	CALL	BDOS
	CALL	HEX
	CALL	CRLF

	LD	DE,MSG_MAKE
	CALL	PRINT
	LD	DE,FCB2
	LD	C,16H		; create
	CALL	BDOS
	CALL	HEX
	LD	HL,WDATA
	LD	DE,DTA
	LD	BC,128
	LDIR
	LD	DE,FCB2
	LD	C,15H		; sequential write
	CALL	BDOS
	CALL	HEX
	LD	DE,FCB2
	LD	C,10H		; close
	CALL	BDOS
	CALL	HEX
	CALL	CRLF

	LD	DE,MSG_BLK
	CALL	PRINT
	LD	DE,FCB3
	LD	C,0FH		; open NEW.TXT
	CALL	BDOS
	CALL	HEX
	LD	HL,1
	LD	(FCB3+14),HL	; record size 1
	LD	HL,4
	LD	(FCB3+33),HL	; random record 4
	LD	HL,0
	LD	(FCB3+35),HL
	LD	DE,DTA
	LD	C,1AH
	CALL	BDOS
	LD	DE,FCB3
	LD	HL,10
	LD	C,27H		; random block read 10 records
	CALL	BDOS
	PUSH	HL
	CALL	HEX
	POP	HL
	LD	A,L
	CALL	HEX
	LD	A,(FCB3+33)	; random record updated
	CALL	HEX
	LD	HL,DTA
	LD	B,10
	CALL	PRTN
	CALL	CRLF

	LD	DE,MSG_SRCH
	CALL	PRINT
	LD	DE,FCB4
	LD	C,11H		; search first
	CALL	BDOS
SLOOP:	OR	A
	JR	NZ,SEND
	LD	HL,DTA+1
	LD	B,11
	CALL	PRTN
	LD	A,' '
	CALL	CHAR
	LD	C,12H		; search next
	CALL	BDOS
	JR	SLOOP
SEND:	CALL	HEX
	CALL	CRLF

	LD	DE,MSG_FSIZ
	CALL	PRINT
	LD	DE,FCB1
	LD	C,23H		; file size
	CALL	BDOS
	CALL	HEX
	LD	A,(FCB1+33)
	CALL	HEX
	CALL	CRLF

	LD	DE,MSG_REN
	CALL	PRINT
	LD	DE,FCB5
	LD	C,17H		; rename NEW.TXT -> REN.TXT
	CALL	BDOS
	CALL	HEX
	LD	DE,FCB6
	LD	C,13H		; delete REN.TXT
	CALL	BDOS
	CALL	HEX
	LD	DE,FCB6
	LD	C,13H		; delete again: not found
	CALL	BDOS
	CALL	HEX
	CALL	CRLF
	LD	DE,MSG_END
	CALL	PRINT
	RET

PRINT:	LD	C,9
	JP	BDOS

CHAR:	PUSH	BC
	PUSH	DE
	PUSH	HL
	LD	E,A
	LD	C,2
	CALL	BDOS
	POP	HL
	POP	DE
	POP	BC
	RET

PRTN:	LD	A,(HL)
	CP	' '
	JR	NC,PR1
	LD	A,'.'
PR1:	CALL	CHAR
	INC	HL
	DJNZ	PRTN
	RET

CRLF:	LD	A,13
	CALL	CHAR
	LD	A,10
	JR	CHAR

HEX:	PUSH	AF
	RRCA
	RRCA
	RRCA
	RRCA
	CALL	NIB
	POP	AF
	CALL	NIB
	LD	A,' '
	JR	CHAR
NIB:	AND	0FH
	ADD	A,'0'
	CP	'9'+1
	JR	C,CHAR
	ADD	A,7
	JR	CHAR

MSG_OPEN: DEFM	"OPEN/READ/CLOSE: $"
MSG_SIZE: DEFM	"SIZE: $"
MSG_MAKE: DEFM	"MAKE/WRITE/CLOSE: $"
MSG_BLK:  DEFM	"BLOCK READ: $"
MSG_SRCH: DEFM	"SEARCH: $"
MSG_FSIZ: DEFM	"FSIZE: $"
MSG_REN:  DEFM	"RENAME/DEL/DEL: $"
MSG_END:  DEFM	"END",13,10,"$"

FCB1:	DEFB	0
	DEFM	"HELLO   TXT"
	DEFS	25,0
FCB2:	DEFB	0
	DEFM	"NEW     TXT"
	DEFS	25,0
FCB3:	DEFB	0
	DEFM	"NEW     TXT"
	DEFS	25,0
FCB4:	DEFB	0
	DEFM	"????????TXT"
	DEFS	25,0
FCB5:	DEFB	0
	DEFM	"NEW     TXT"
	DEFB	0,0,0,0,0
	DEFM	"REN     TXT"
	DEFS	9,0
FCB6:	DEFB	0
	DEFM	"REN     TXT"
	DEFS	25,0
WDATA:	DEFM	"0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ written with FCB"
	DEFS	128-53,1AH
